using BotAimImprover;
int checks=0;
void Check(string name,bool actual) { if(!actual) throw new Exception(name); checks++; Console.WriteLine("PASS "+name); }
AimLocation zero=new(0,0,0), far=new(1000,0,0);
Check("nearby audible step",AwarenessPolicy.Audible(zero,new(100,0,0),720,false,true));
Check("distant footstep not heard",!AwarenessPolicy.Audible(zero,far,720,false,true));
Check("range from actual event honored",!AwarenessPolicy.Audible(zero,new(100,0,0),50,false,true));
Check("zero-radius event rejected",!AwarenessPolicy.Audible(zero,zero,0,false,true));
Check("unbounded footsteps capped",!AwarenessPolicy.Audible(zero,far,99999,false,true));
Check("wall attenuates distant steps",!AwarenessPolicy.Audible(zero,new(400,0,0),720,true,true));
Check("close muffled step still audible",AwarenessPolicy.Audible(zero,new(100,0,0),720,true,true));
Check("different distant floor rejected",!AwarenessPolicy.Audible(zero,new(20,20,400),720,false,true));
Check("invalid source rejected",!AwarenessPolicy.Audible(zero,new(float.NaN,0,0),720,false,true));
Check("invalid listener rejected",!AwarenessPolicy.Audible(new(float.NaN,0,0),zero,720,false,true));
Check("invalid radius rejected",!AwarenessPolicy.Audible(zero,zero,float.NaN,false,true));
Check("shot range also capped",!AwarenessPolicy.Audible(zero,new(2000,0,0),99999,false,false));
var point=new AimLocation(137,291,80); var heard=AwarenessPolicy.Hear(point,10,true,null);
Check("hearing has reaction delay",!heard.Ready(10.34f));
Check("ready after reaction delay",heard.Ready(10.36f));
Check("step memory expires",!heard.Ready(12.21f));
var refreshed=AwarenessPolicy.Hear(point,10.1f,true,heard);
Check("repeated steps do not restart pending reaction",Math.Abs(refreshed.ReadyAt-heard.ReadyAt)<0.001);
Check("long-expired cue not revived implicitly",!heard.Ready(90));
var snapshot=heard.Position;
point=new(900,900,80);
Check("memory is a snapshot not live enemy location",heard.Position==snapshot);
var approx=AwarenessPolicy.Approximate(new(137,291,80),3,7);
Check("heard position deliberately imprecise",approx!=new AimLocation(137,291,80));
Check("per-event error stable",approx==AwarenessPolicy.Approximate(new(137,291,80),3,7));
Check("listeners have independent uncertainty",approx!=AwarenessPolicy.Approximate(new(137,291,80),4,7));
Check("hearing error remains local",AwarenessPolicy.Distance(approx,new(137,291,80))<80);
var aim=AwarenessPolicy.Bearing(new(0,0,64),new(0,20,0));
Check("close sound turns toward it",Math.Abs(aim.X)<0.01 && aim.Y>500);
Check("blind sound aim stays at eye height",aim.Z==64);
Check("only one of two bots yields",AwarenessPolicy.Yields(3,2,false,false) && !AwarenessPolicy.Yields(2,3,false,false));
Check("human has priority",AwarenessPolicy.Yields(1,3,true,false));
Check("defuser has priority",AwarenessPolicy.Yields(1,3,false,true));
Check("freeze-time assistance rejected",!AwarenessPolicy.CanAssist(false,false,false,true,false));
Check("objective/replay assistance rejected",!AwarenessPolicy.CanAssist(true,true,false,true,false));
Check("human-controlled pawn rejected",!AwarenessPolicy.CanAssist(true,false,true,true,false));
Check("airborne or ladder assistance rejected",!AwarenessPolicy.CanAssist(true,false,false,false,false));
Check("visible combat keeps priority",!AwarenessPolicy.CanAssist(true,false,false,true,true));
Check("idle grounded bot eligible",AwarenessPolicy.CanAssist(true,false,false,true,false));
Console.WriteLine($"PASS {checks} awareness checks");
